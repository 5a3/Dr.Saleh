// State Variables
let currentLang = localStorage.getItem('site_lang') || 'ar';
let currentTheme = localStorage.getItem('site_theme') || 'light';

// Initialize Theme
function applyTheme(theme) {
  currentTheme = theme;
  localStorage.setItem('site_theme', theme);
  if (theme === 'dark') {
    document.documentElement.setAttribute('data-theme', 'dark');
  } else {
    document.documentElement.removeAttribute('data-theme');
  }

  const themeBtnIcon = document.querySelector('#themeToggleBtn i');
  if (themeBtnIcon) {
    if (theme === 'dark') {
      themeBtnIcon.className = 'fa-solid fa-sun';
    } else {
      themeBtnIcon.className = 'fa-solid fa-moon';
    }
  }
}

function toggleTheme() {
  const nextTheme = currentTheme === 'light' ? 'dark' : 'light';
  applyTheme(nextTheme);
}

// Language Switcher
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('site_lang', lang);
  
  const htmlEl = document.documentElement;
  htmlEl.lang = lang;
  htmlEl.dir = lang === 'ar' ? 'rtl' : 'ltr';

  const dict = translations[lang] || translations['ar'];

  // Update Page Title
  const titleEl = document.getElementById('pageTitle');
  if (titleEl && dict.page_title) {
    titleEl.innerText = dict.page_title;
  }

  // Update text elements with [data-i18n]
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerText = dict[key];
    }
  });

  // Update Placeholders with [data-i18n-placeholder]
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Update Switcher Button Text
  const langLabel = document.getElementById('langLabel');
  if (langLabel) {
    langLabel.innerText = dict.lang_switch_label;
  }
}

function toggleLanguage() {
  const nextLang = currentLang === 'ar' ? 'en' : 'ar';
  setLanguage(nextLang);
}

// Initialize on DOM Ready
document.addEventListener('DOMContentLoaded', () => {
  applyTheme(currentTheme);
  setLanguage(currentLang);

  // Mobile Menu Toggle
  const navToggle = document.getElementById('navToggle');
  const navLinks = document.getElementById('navLinks');
  const navItems = document.querySelectorAll('.nav-link');

  if (navToggle && navLinks) {
    navToggle.addEventListener('click', () => {
      navLinks.classList.toggle('active');
      document.body.classList.toggle('menu-open');
      const icon = navToggle.querySelector('i');
      if (icon) {
        if (navLinks.classList.contains('active')) {
          icon.classList.replace('fa-bars', 'fa-xmark');
        } else {
          icon.classList.replace('fa-xmark', 'fa-bars');
        }
      }
    });

    navItems.forEach(item => {
      item.addEventListener('click', () => {
        navLinks.classList.remove('active');
        document.body.classList.remove('menu-open');
        const icon = navToggle.querySelector('i');
        if (icon) icon.classList.replace('fa-xmark', 'fa-bars');
      });
    });
  }

  // Active Link Scroll Highlighting & Scroll Animations
  const sections = document.querySelectorAll('section[id], footer[id]');
  const animatedElements = document.querySelectorAll('.animate-on-scroll');

  const scrollObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, { threshold: 0.15 });

  animatedElements.forEach(el => scrollObserver.observe(el));

  window.addEventListener('scroll', () => {
    let current = '';
    const scrollPosition = window.pageYOffset + 150;

    sections.forEach(section => {
      const sectionTop = section.offsetTop;
      const sectionHeight = section.offsetHeight;
      if (scrollPosition >= sectionTop && scrollPosition < sectionTop + sectionHeight) {
        current = section.getAttribute('id');
      }
    });

    if (Math.ceil(window.innerHeight + window.scrollY) >= document.documentElement.scrollHeight - 10) {
      if (sections.length > 0) {
        current = sections[sections.length - 1].getAttribute('id');
      }
    }

    navItems.forEach(link => {
      link.classList.remove('active');
      if (link.getAttribute('href') === `#${current}`) {
        link.classList.add('active');
      }
    });
  });
});

// Interactive Book Modal by Key
function openBookModalKey(bookKey, imgSrc) {
  const dict = translations[currentLang] || translations['ar'];
  const title = dict[`${bookKey}_title`] || '';
  const desc = dict[`${bookKey}_desc`] || '';

  const titleEl = document.getElementById('modalBookTitle');
  const descEl = document.getElementById('modalBookDesc');
  const imgEl = document.getElementById('modalBookImg');

  if (titleEl) titleEl.innerText = title;
  if (descEl) descEl.innerText = desc;

  if (imgEl) {
    if (imgSrc) {
      imgEl.src = imgSrc;
      imgEl.style.display = 'block';
    } else {
      imgEl.style.display = 'none';
    }
  }

  const modal = document.getElementById('bookModal');
  if (modal) modal.classList.add('active');
}

function closeModalDirect() {
  const modal = document.getElementById('bookModal');
  if (modal) modal.classList.remove('active');
}

function closeBookModal(e) {
  if (e.target.id === 'bookModal') {
    closeModalDirect();
  }
}

